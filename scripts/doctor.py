sys.path.insert(0, str(ROOT / "scripts"))

import dev_ports
import env_secrets

COLORS = {"OK": "32", "INFO": "34", "WARN": "33", "FAIL": "31"}
LEVELS = tuple(COLORS)
OPENAPI_JSON = ROOT / "docs" / "openapi" / "openapi.json"
OPENAPI_ENV = {"DJANGO_SETTINGS_MODULE": "api.settings.test", "SECRET_KEY": "x"}
# The pool waits 10s for a refused connection and hides the reason.
DEV_DB_ENV = {"DJANGO_SETTINGS_MODULE": "api.settings.dev", "DB_POOL_ENABLED": "false"}
HOOKS = ("pre-commit", "commit-msg", "pre-push")
PRE_COMMIT_MARKER = "File generated by pre-commit"
PORT_LABELS = {
    "POSTGRES_PORT": "Postgres",
    "VALKEY_PORT": "Valkey",
    "DJANGO_PORT": "Django",
    "FLOWER_PORT": "Flower",
}
# Postgres SSLRequest: length 8, code 80877103. A server answers S, N or E.
SSL_REQUEST = struct.pack("!ii", 8, 80877103)


@dataclass
class Fix:
    """A repair for one check."""

    commands: list[list[str]]
    env: dict[str, str] = field(default_factory=dict)
    needs_yes: bool = False
    manual: bool = False
    """Print only: doctor cannot or must not run it."""
    preview: list[str] | None = None
    """Run when the fix is skipped for lack of ``--yes`` (a dry run)."""
    watch: Path | None = None
    """Report whether this file changed."""

    def display(self) -> str:
        prefix = " ".join(f"{key}={value}" for key, value in self.env.items())
        lines = [shlex.join(command) for command in self.commands]
        return " && ".join(f"{prefix} {line}" if prefix else line for line in lines)

    @property
    def mode(self) -> str:
        """``manual`` (print only), ``needs_yes``, or ``auto`` (``--fix``)."""
        if self.manual:
            return "manual"
        return "needs_yes" if self.needs_yes else "auto"


@dataclass
class Check:
    """One diagnosis line, its fix, and the fix outcome."""

    id: str
    level: str
    message: str
    hint: str = ""
    fix: Fix | None = None
    fixed: bool = False
    result: str = ""

    def as_json(self) -> dict[str, object]:
        fix = self.fix
        return {
            "id": self.id,
            "level": self.level,
            "message": self.message,
            "hint": self.hint,
            "fix": fix.display() if fix else None,
            "fix_mode": fix.mode if fix else None,
            "fixed": self.fixed,
            "result": self.result,
        }


checks: list[Check] = []


def add(
    check_id: str, level: str, message: str, hint: str = "", fix: Fix | None = None
) -> Check:
    check = Check(check_id, level, message, hint, fix)
    checks.append(check)
    return check


def run(
    args: list[str], timeout: float = 10, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str] | None:
    try:
        return subprocess.run(
            args,
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
            env={**os.environ, **env} if env else None,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None


def last_line(result: subprocess.CompletedProcess[str] | None) -> str:
    if result is None:
        return "command not found or timed out"
    lines = (result.stderr.strip() or result.stdout.strip()).splitlines()
    return lines[-1].strip() if lines else f"exit {result.returncode}"


def check_tools() -> None:
    version = sys.version_info
    if version >= (3, 11):
        add("python", "OK", f"Python {version.major}.{version.minor}.{version.micro}")
    else:
        add(
            "python",
            "FAIL",
            f"Python {version.major}.{version.minor} is too old",
            "use 3.11+",
        )
    for tool, hint in (
        ("uv", "curl -LsSf https://astral.sh/uv/install.sh | sh"),
        ("just", "brew install just"),
    ):
        if shutil.which(tool):
            add(tool, "OK", f"{tool} found ({last_line(run([tool, '--version']))})")
        else:
            add(tool, "FAIL", f"{tool} not found", hint)
    if shutil.which("git"):
        add("git", "OK", "git found")
    else:
        add("git", "WARN", "git not found", "install git")


def check_docker() -> bool:
    """Report Docker and Compose; return True when the daemon answers."""
    if not shutil.which("docker"):
        add(
            "docker",
            "WARN",
            "docker not installed",
            "needed for `just dev`; install OrbStack",
        )
        return False
    info = run(["docker", "info", "--format", "{{.ServerVersion}}"], timeout=15)
    up = info is not None and info.returncode == 0
    if up:
        add("docker", "OK", f"Docker {info.stdout.strip()} is running")
    else:
        add(
            "docker",
            "WARN",
            "Docker daemon is down",
            "start OrbStack before `just dev`",
        )
    compose = run(["docker", "compose", "version", "--short"])
    if compose is not None and compose.returncode == 0:
        add("compose", "OK", f"Docker Compose {compose.stdout.strip()}")
    else:
        add(
            "compose",
            "WARN",
            "docker compose plugin not found",
            "install Docker Compose v2",
        )
    return up


