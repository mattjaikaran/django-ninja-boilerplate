def check_env_files(env: dict[str, str]) -> None:
    env_path = ROOT / ".env"
    if not env_path.is_file():
        create = Fix([["python3", "scripts/env_secrets.py", "create"]])
        add(
            "env.file",
            "FAIL",
            ".env not found",
            "creates it with fresh secrets",
            create,
        )
        return
    add("env.file", "OK", ".env exists")
    required = ("SECRET_KEY", "DB_NAME", "DB_USER", "DB_PASSWORD")
    missing = [key for key in required if key not in env]
    if missing:
        add(
            "env.keys",
            "WARN",
            f".env is missing keys: {', '.join(missing)}",
            "copy them from .env.example",
        )
    dev_path = ROOT / ".env.development"
    if dev_path.is_file():
        dev = env_secrets.read_env(dev_path)
        differ = [
            k
            for k in ("DB_HOST", "DB_PORT")
            if k in env and k in dev and env[k] != dev[k]
        ]
        if differ:
            add(
                "env.agree",
                "WARN",
                f".env and .env.development differ on: {', '.join(differ)}",
                "align them so manage.py and the Docker stack hit the same DB",
            )
        else:
            add(
                "env.agree",
                "OK",
                "DB_HOST/DB_PORT agree between .env and .env.development",
            )
    check_secrets(env_path, env)


def check_secrets(env_path: Path, env: dict[str, str]) -> None:
    """FAIL on unset secrets (Compose refuses to start), WARN on weak ones."""
    unset = [
        s.name for s in env_secrets.SECRETS if env_secrets.is_unset(s, env.get(s.name))
    ]
    weak = [n for n in env_secrets.weak_secrets(env_path) if n not in unset]
    plan = env_secrets.plan_fill(env_path)
    fill = None
    if plan.names:
        fill = Fix(
            [["python3", "scripts/env_secrets.py", "fill"]],
            needs_yes=True,
            preview=["python3", "scripts/env_secrets.py", "fill", "--dry-run"],
        )
    if unset:
        hint = ""
        if plan.skipped:
            hint = (
                f"placeholder kept by fill because a data volume stores it: "
                f"{', '.join(plan.skipped)}; set the password that volume uses"
            )
        add(
            "env.secrets",
            "FAIL",
            f"unset secrets in .env: {', '.join(unset)}",
            hint,
            fill,
        )
    if weak:
        hint = "fill keeps values you chose; replace them by hand"
        add(
            "env.weak",
            "WARN",
            f"weak secrets in .env: {', '.join(weak)}",
            hint,
            None if unset else fill,
        )
    if not unset and not weak:
        add(
            "env.secrets",
            "OK",
            f"all {len(env_secrets.SECRETS)} generated secrets are set",
        )


