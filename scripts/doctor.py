#!/usr/bin/env python3
"""Agent and developer preflight for the Django Ninja Boilerplate.

Each check prints one line: OK, INFO, WARN, or FAIL, with a hint. A check
can carry a fix. ``--fix`` runs the safe fixes and prints each command and
its result: FIXED, SKIPPED (needs --yes), or FAILED <reason>. Fixes that
change the database, remove worktrees, or rewrite ``.env`` secrets run only
with ``--yes``. Manual steps (start the stack, ``unset CI``) are printed,
never run. ``--json`` prints the checks as JSON for agents.

The script never prints secret values; it names keys only.

Exit codes: 0 when no check fails (after fixes), 1 when a FAIL remains.

Usage:
    ./scripts/doctor.sh [--fix] [--yes] [--json]
    python3 scripts/doctor.py [--fix] [--yes] [--json]
"""

